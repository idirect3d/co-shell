_SRC = 'i18n/en.go'
_KEYS = {f'KeyCmdMig_{i:03d}' for i in range(1, 382)}


def main() -> int:
    with open(_SRC, encoding='utf-8') as f:
        lines = f.readlines()

    changed = 0
    missing = []
    out = []
    # Line format: '\tKeyCmdMig_001:             "value",'  (optional trailing comma)
    key_re = re.compile(r'^(\s*)(KeyCmdMig_\d+):\s*"(.*)"(?:,)?\s*$')
    for line in lines:
        m = key_re.match(line.rstrip('\n'))
        if m:
            indent, key, _ = m.group(1), m.group(2), m.group(3)
            if key in EN:
                out.append(f'{indent}{key}:\t\t\t"{EN[key]}",\n')
                changed += 1
                continue
            if key in _KEYS and key not in EN:
                missing.append(key)
        out.append(line)

    if missing:
        missing_sorted = sorted(missing, key=lambda k: int(k.rsplit('_', 1)[1]))
        print(f'Missing translations for {len(missing_sorted)} keys:')
        for k in missing_sorted:
            print(f'  {k}')
        print('Aborting — no changes written.')
        return 1

    with open(_SRC, 'w', encoding='utf-8') as f:
        f.writelines(out)
    print(f'Replaced {changed} Chinese values in {_SRC}.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())